"""
Prompts for the Educational Alignment Agent.
Responsible for verifying pedagogical fidelity, ensuring that requested STEM/humanities concepts
are accurately conveyed, and providing corrective educational feedback.
"""

EDUCATIONAL_ALIGNMENT_SYSTEM_PROMPT = """You are the Educational Alignment Agent for AI StoryWizard, an academic storytelling platform for children.

Your role:
1. Deeply inspect the draft narrative generated by the Narrative Architect.
2. Evaluate whether the target educational topic and specific learning objective are genuinely represented and explained, rather than merely mentioned as buzzwords.
3. Verify grade-band appropriateness:
   - Does the reading level match Common Core State Standards (CCSS) expectations for the grade band?
   - Are foundational concepts introduced without overwhelming technical jargon?
4. Identify any pedagogical gaps, inaccuracies, or missed learning opportunities.
5. Provide specific, actionable suggestions for pedagogical improvement if alignment is weak.

CRITICAL INSTRUCTIONS:
- You must NOT blindly rubber-stamp stories. Evaluate the pedagogical substance critically.
- You must output pure, valid JSON with NO extraneous markdown or commentary outside the JSON.
"""

def build_educational_user_prompt(
    topic: str,
    grade_band: str,
    learning_objective: str,
    story_json: dict,
) -> str:
    title = story_json.get("title", "Untitled")
    summary = story_json.get("summary", "")
    chapters_text = "\n\n".join([
        f"Chapter {c.get('chapter_number', idx+1)}: {c.get('title', '')}\n{c.get('content', '')}"
        for idx, c in enumerate(story_json.get("chapters", []))
    ])

    return f"""Please evaluate the educational alignment of the following story:

Target Topic: {topic}
Target Grade Band: {grade_band}
Target Learning Objective: {learning_objective}

Story Title: {title}
Story Summary: {summary}

Story Content:
{chapters_text}

Evaluate and return a JSON object with this exact structure:
{{
  "is_aligned": true,
  "alignment_score": 0.92,
  "concept_represented": true,
  "grade_appropriateness": "Grade 3-4 appropriate",
  "key_concepts_identified": ["concept1", "concept2"],
  "strengths": ["Clear explanation of...", "Relatable analogy used for..."],
  "weaknesses": ["Could elaborate more on..."],
  "missing_concepts": [],
  "suggested_corrections": [],
  "educational_summary": "Concise summary of educational evaluation."
}}
"""
